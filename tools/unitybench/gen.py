#!/usr/bin/env python3
"""Generate unitybench.c: the call shapes of a Unity/Mono steady state, without Unity.

Read from Subnautica's binaries (see README in unitybench.sh):

* JIT code reaches the runtime with `movabs r11, imm64; call r11`, because the code
  manager's pages are further than 2 GiB from libmono and UnityPlayer. Every
  managed->native wrapper calls `mono_tls_get_lmf_addr`, every reference store calls
  the write barrier (`GC_dirty_inner`), and icalls land in UnityPlayer.
* Managed code dispatches through vtables, `call [rax+disp32]`.
* UnityPlayer's icalls dispatch through C++ vtables of their own.

Each of those is an indirect call to the lifter, and each callee's `ret` leaves its
region. The point is the *working set*: thousands of distinct targets and return
addresses per frame, which is what a direct-mapped link table has to hold.

UnityPlayer's hot functions are scattered through 24 MiB of text, so each native
function ends in a never-taken block of up to PAD bytes (pseudo-random, so no regular
stride aliases); Mono's JIT code stays densely packed, as its code manager packs it.

usage: gen.py OUT.c [managed_classes] [icalls] [native_classes] [pad]
"""

import sys

out = sys.argv[1]
MCLASSES = int(sys.argv[2]) if len(sys.argv) > 2 else 1024
ICALLS = int(sys.argv[3]) if len(sys.argv) > 3 else 1024
NCLASSES = int(sys.argv[4]) if len(sys.argv) > 4 else 512
PAD = int(sys.argv[5]) if len(sys.argv) > 5 else 8192


def pad(k, var):
    """A never-taken block of cold bytes, which block placement puts after `k`'s hot path."""
    n = (k * 2654435761 >> 7) % (PAD + 1) if PAD else 0
    if not n:
        return ""
    return (f"    if (__builtin_expect({var} == 0x5eed{k:04x}, 0))\n"
            f'        __asm__ volatile(".space {n}, 0xcc");\n')

c = []
w = c.append

w(f"""// Generated by tools/unitybench/gen.py; do not edit.
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/mman.h>
#include <time.h>

#define MCLASSES {MCLASSES}
#define ICALLS {ICALLS}
#define NCLASSES {NCLASSES}
#define NOBJS 4096
#define NCARDS 4096

typedef struct MObj {{ void **vtable; long acc; struct MObj *child; long id; }} MObj;
typedef struct NObj NObj;
typedef struct NVt {{ long (*m[4])(NObj *, long); }} NVt;
struct NObj {{ const NVt *vt; long state; }};

static NVt nvts[NCLASSES];
static NObj natives[NOBJS];
static volatile unsigned char cards[NCARDS];
static void *lmf_slot;

// libmono stand-ins, reached from JIT code by absolute address.
__attribute__((noinline)) void **rt_lmf_addr(void) {{ return &lmf_slot; }}
__attribute__((noinline)) void rt_wbarrier(MObj *o) {{ cards[((uintptr_t)o >> 6) & (NCARDS - 1)] = 1; }}
""")

# UnityPlayer stand-ins: varied bodies, so the native side has a real footprint and
# real per-function resume points rather than a few identical stubs.
for k in range(NCLASSES * 4):
    a, b, n = (k * 2654435761) & 0xFFFF | 1, (k * 40503) & 0xFFF, 1 + k % 4
    body = "".join(f"    x = (x * {a + i} + {b ^ i}) ^ (x >> {3 + i});\n" for i in range(n))
    w(f"__attribute__((noinline)) static long nm{k}(NObj *o, long x) {{\n{body}"
      f"{pad(k, 'x')}    o->state += x & 0xff;\n    return x;\n}}\n")

for k in range(ICALLS):
    w(f"__attribute__((noinline)) long ic{k}(MObj *m) {{\n"
      f"    NObj *n = &natives[(m->id * 31 + {k}) & (NOBJS - 1)];\n"
      f"    long r = n->vt->m[{k & 3}](n, m->acc);\n"
      f"    r += n->vt->m[{(k >> 2) & 3}](n, r);\n"
      f"{pad(NCLASSES * 4 + k, 'r')}    return r & 0xffff;\n}}\n")

w("static long (*const nmeths[])(NObj *, long) = {" +
  ",".join(f"nm{k}" for k in range(NCLASSES * 4)) + "};\n")
w("static long (*const icalls[])(MObj *) = {" +
  ",".join(f"ic{k}" for k in range(ICALLS)) + "};\n")

w(r"""
// The JIT: one method per vtable slot, emitted the way Mono's amd64 backend emits a
// managed->native wrapper with a far target.
static unsigned char *jp;
static void b(int n, ...) { __builtin_va_list ap; __builtin_va_start(ap, n);
    while (n--) *jp++ = (unsigned char)__builtin_va_arg(ap, int); __builtin_va_end(ap); }
static void far_call(void *target) {
    b(2, 0x49, 0xbb); memcpy(jp, &target, 8); jp += 8;  // movabs r11, target
    b(3, 0x41, 0xff, 0xd3);                              // call r11
}

static void *emit_method(int slot, void *icall) {
    jp = (unsigned char *)(((uintptr_t)jp + 15) & ~(uintptr_t)15);
    void *entry = jp;
    b(1, 0x53); b(2, 0x41, 0x54); b(4, 0x48, 0x83, 0xec, 0x08);   // push rbx; push r12; sub rsp,8
    b(3, 0x48, 0x89, 0xfb);                                        // mov rbx, rdi
    far_call((void *)rt_lmf_addr);                                 // LMF push
    b(3, 0x49, 0x89, 0xc4);                                        // mov r12, rax
    b(3, 0x49, 0x89, 0x1c); b(1, 0x24);                            // mov [r12], rbx
    b(3, 0x48, 0x89, 0xdf);                                        // mov rdi, rbx
    far_call(icall);                                               // the icall
    b(4, 0x48, 0x01, 0x43, 0x08);                                  // add [rbx+8], rax
    b(4, 0x49, 0xc7, 0x04, 0x24); b(4, 0, 0, 0, 0);                // mov qword [r12], 0
    b(3, 0x48, 0x89, 0xdf);                                        // mov rdi, rbx
    far_call((void *)rt_wbarrier);                                 // write barrier
    if (slot == 0) {
        b(4, 0x48, 0x8b, 0x7b, 0x10);                              // mov rdi, [rbx+16]
        b(3, 0x48, 0x85, 0xff); b(2, 0x74, 0x0d);                  // test rdi,rdi; jz +13
        b(3, 0x48, 0x8b, 0x07);                                    // mov rax, [rdi]
        b(2, 0xff, 0x90); int d = 8 * (1 + 0); memcpy(jp, &d, 4); jp += 4;  // call [rax+8]
        b(4, 0x48, 0x01, 0x43, 0x08);                              // add [rbx+8], rax
    }
    b(4, 0x48, 0x8b, 0x43, 0x08);                                  // mov rax, [rbx+8]: no stale helper rax
    b(4, 0x48, 0x83, 0xc4, 0x08); b(2, 0x41, 0x5c); b(1, 0x5b); b(1, 0xc3);
    return entry;
}

static uint64_t rng = 0x9e3779b97f4a7c15ull;
static uint64_t next(void) { rng ^= rng << 13; rng ^= rng >> 7; rng ^= rng << 17; return rng; }

static double now(void) {
    struct timespec t; clock_gettime(CLOCK_MONOTONIC, &t); return t.tv_sec + t.tv_nsec * 1e-9;
}

int main(int argc, char **argv) {
    int frames = argc > 1 ? atoi(argv[1]) : 100;
    int used = argc > 2 ? atoi(argv[2]) : MCLASSES;   // classes in play: the working set
    if (used < 1 || used > MCLASSES) used = MCLASSES;

    for (int c = 0; c < NCLASSES; c++)
        for (int s = 0; s < 4; s++) nvts[c].m[s] = nmeths[c * 4 + ((s + c) & 3)];
    for (int i = 0; i < NOBJS; i++) { natives[i].vt = &nvts[next() % NCLASSES]; natives[i].state = i; }

    size_t size = (size_t)MCLASSES * 2 * 128;
    unsigned char *code = mmap(0, size, PROT_READ | PROT_WRITE | PROT_EXEC,
                               MAP_PRIVATE | MAP_ANON | MAP_JIT, -1, 0);
    if (code == MAP_FAILED) { perror("mmap"); return 1; }
    jp = code;
    void ***vtables = calloc(MCLASSES, sizeof *vtables);
    for (int c = 0; c < MCLASSES; c++) {
        vtables[c] = calloc(2, sizeof(void *));
        for (int s = 0; s < 2; s++)
            vtables[c][s] = emit_method(s, (void *)icalls[(c * 2 + s) * 2654435761u % ICALLS]);
    }

    MObj *objs = calloc(NOBJS, sizeof *objs);
    int *order = calloc(NOBJS, sizeof *order);
    for (int i = 0; i < NOBJS; i++) {
        objs[i].vtable = vtables[next() % used];
        objs[i].id = i;
        order[i] = i;
    }
    for (int i = 0; i < NOBJS; i++)
        objs[i].child = (i & 1) ? &objs[next() % NOBJS] : 0;
    for (int i = NOBJS - 1; i > 0; i--) { int j = next() % (i + 1); int t = order[i]; order[i] = order[j]; order[j] = t; }

    long sum = 0;
    double t0 = now(), warm = 0;
    for (int f = 0; f < frames; f++) {
        for (int i = 0; i < NOBJS; i++) {
            MObj *o = &objs[order[i]];
            ((void (*)(MObj *))o->vtable[0])(o);   // MonoBehaviour.Update
        }
        if (f == 0) warm = now() - t0;
    }
    double total = now() - t0;
    for (int i = 0; i < NOBJS; i++) sum += objs[i].acc + natives[i].state;
    printf("unitybench: %d frame(s), %d of %d classes, first %.1f ms, steady %.3f ms/frame, checksum %ld\n",
           frames, used, MCLASSES, warm * 1e3, frames > 1 ? (total - warm) * 1e3 / (frames - 1) : 0.0, sum);
    return 0;
}
""")

with open(out, "w") as f:
    f.write("".join(c))
