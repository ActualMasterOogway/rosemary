#!/usr/bin/env python3
"""Call the generated bridge the way a guest does, and check what arrives.

The dylib itself is Mach-O, but its sources are freestanding and the ABI it
targets - Itanium C++, LP64 - is the host's too, so the same sources build
natively and can be driven through their vtables exactly as a guest drives
them: find the interface, index the vtable, call. A stub dispatch stands in
for the host Steam client and records what it was handed.

Usage:
    smoke_test.py --generated DIR [--cxx g++]
"""

import argparse
import json
import os
import subprocess
import sys
import tempfile

# Each case: interface version, method, the argument list to pass, and the
# value the stub dispatch should hand back.
CASES = [
    ("STEAMAPPS_INTERFACE_VERSION008", "BIsSubscribedApp",
     [("uint32_t", "1234")], "bool", "true"),
    ("STEAMAPPS_INTERFACE_VERSION008", "GetCurrentGameLanguage",
     [], "const char *", '(const char *)"english"'),
    ("SteamUser023", "GetSteamID", [], "CSteamID", "CSteamID{0x110000100000001ull}"),
    ("SteamUser023", "InitiateGameConnection_DEPRECATED",
     [("void *", "(void *)0x1000"), ("int32_t", "64"), ("CSteamID", "CSteamID{7}"),
      ("uint32_t", "0x7f000001"), ("uint16_t", "27015"), ("bool", "true")],
     "int32_t", "42"),
]

MAIN = r'''/* Generated by tools/steamclient/smoke_test.py. */
#include "rosetta3_steam.h"
#include "steamclient_methods.h"

extern "C" int printf(const char *, ...);
extern "C" void *CreateInterface(const char *name, int32_t *return_code);

static int failures;

#define CHECK(cond) do { \
    if (!(cond)) { printf("  FAIL %%s:%%d: %%s\n", __FILE__, __LINE__, #cond); ++failures; } \
} while (0)

static uint32_t last_method = 0xffffffff;
static void *last_params;
static unsigned char params_copy[512];

/* Stands in for the host Steam client. */
extern "C" int32_t rosetta3_steamclient_dispatch(uint32_t method, void *params)
{
    last_method = method;
    last_params = params;

    if (method == STEAM_DISPATCH_CREATE_INTERFACE)
    {
        steam_params_create_interface *p = (steam_params_create_interface *)params;
        p->_ret = (void *)0xfeed1234;
        return STEAM_DISPATCH_OK;
    }

%(returns)s
    return STEAM_DISPATCH_OK;
}

template <typename T> static T load(void *base, unsigned offset)
{
    T value;
    __builtin_memcpy(&value, (unsigned char *)base + offset, sizeof(T));
    return value;
}

int main(void)
{
%(cases)s
    printf("%%s: %%d failure(s)\n", failures ? "FAILED" : "ok", failures);
    return failures != 0;
}
'''


def find(manifest, version, method_name):
    for iface in manifest["interfaces"]:
        if iface["version"] != version:
            continue
        for method in iface["methods"]:
            if method["name"] == method_name:
                return iface, method
    raise SystemExit(f"{version}.{method_name} is not in the manifest")


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--generated", default=os.path.join(here, "generated"))
    parser.add_argument("--cxx", default=os.environ.get("CXX", "g++"))
    args = parser.parse_args()

    manifest = json.load(open(os.path.join(args.generated, "steamclient_manifest.json")))

    returns, cases = [], []
    for version, name, call_args, ret_type, ret_value in CASES:
        iface, method = find(manifest, version, name)
        returns.append(
            f"    if (method == {method['id']})\n    {{\n"
            f"        __builtin_memcpy(params_copy, params, {method['params_size']});\n"
            + (f"        *({ret_type} *)((unsigned char *)params + "
               f"{method['ret']['offset']}) = {ret_value};\n" if method["ret"] else "")
            + "        return STEAM_DISPATCH_OK;\n    }\n")

        signature = ', '.join(["void *"] + [t for t, _ in call_args])
        body = [
            f'    printf("{version}.{name}\\n");',
            '    {',
            f'        void *iface = CreateInterface("{version}", nullptr);',
            '        CHECK(iface != nullptr);',
            '        void **vtable = *(void ***)iface;',
            f'        auto fn = ({ret_type} (*)({signature}))'
            f'vtable[{method["vtable_index"]}];',
        ]
        for i, (type, value) in enumerate(call_args):
            body.append(f'        {type} arg{i} = {value};')
        values = ', '.join(["iface"] + [f"arg{i}" for i in range(len(call_args))])
        body.append(f'        {"auto ret = " if method["ret"] else ""}fn({values});')
        body.append(f'        CHECK(last_method == {method["id"]});')
        body.append('        CHECK(load<void *>(params_copy, 0) == (void *)0xfeed1234);')
        # Compare raw bytes: by-value struct types have no operator==.
        for i, param in enumerate(method["params"]):
            body.append(f'        CHECK(!__builtin_memcmp(params_copy + '
                        f'{param["offset"]}, &arg{i}, sizeof arg{i}));')
        if method["ret"]:
            body.append(f'        {ret_type} expected = {ret_value};')
            body.append('        CHECK(!__builtin_memcmp(&ret, &expected, sizeof ret));')
        body.append('    }')
        cases.append('\n'.join(body))

    sources = [os.path.join(args.generated, s) for s in manifest["sources"]]
    with tempfile.TemporaryDirectory() as tmp:
        main_path = os.path.join(tmp, "smoke_main.cpp")
        with open(main_path, "w") as f:
            f.write(MAIN % {"returns": ''.join(returns), "cases": '\n\n'.join(cases)})

        binary = os.path.join(tmp, "smoke")
        compile = [args.cxx, "-std=c++17", "-O1", "-fno-rtti", "-fno-exceptions",
                   "-w", f"-I{args.generated}", "-o", binary, main_path] + sources
        result = subprocess.run(compile)
        if result.returncode:
            return result.returncode
        return subprocess.run([binary]).returncode


if __name__ == "__main__":
    sys.exit(main())
