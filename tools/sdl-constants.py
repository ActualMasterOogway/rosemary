#!/usr/bin/env python3
"""Write crates/sdl3/src/{keycodes,mouse}.rs from SDL3's own headers.

The numbers these files hold are an ABI this tree does not control, and one
transcribed by hand is a keystroke or a mouse button that is merely *wrong* -
which is the failure that is hardest to see from inside the runtime. So they
are parsed out of the headers instead, and the tables that consume them name
the constants rather than repeating the numbers.

    tools/sdl-constants.py [--include-dir DIR] [--check]

The include directory defaults to whatever `pkg-config --cflags sdl3` names.
`--check` regenerates into memory and fails if the tree disagrees, which is
what CI would run.
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "crates" / "sdl3" / "src"

BANNER = """// Generated by tools/sdl-constants.py from {header}. Do not edit.
"""


def include_dir() -> Path:
    out = subprocess.run(
        ["pkg-config", "--cflags-only-I", "sdl3"],
        capture_output=True,
        text=True,
    )
    if out.returncode == 0:
        for flag in out.stdout.split():
            if flag.startswith("-I"):
                candidate = Path(flag[2:]) / "SDL3"
                if (candidate / "SDL_scancode.h").exists():
                    return candidate
    sys.exit("no SDL3 headers: pass --include-dir with the directory holding SDL_scancode.h")


def rust_name(name: str) -> str:
    # A scancode named for a digit cannot be a Rust identifier on its own.
    return "KEY_" + name if name[0].isdigit() else name


def scancodes(header: Path) -> list[tuple[str, int]]:
    body = header.read_text()
    enum = re.search(r"typedef enum SDL_Scancode\s*\{(.*?)\}", body, re.S)
    if not enum:
        sys.exit(f"{header}: no SDL_Scancode enum")
    found = re.findall(r"^\s*SDL_SCANCODE_(\w+)\s*=\s*(\d+)", enum.group(1), re.M)
    return [(rust_name(n), int(v)) for n, v in found if n != "COUNT"]


def defines(header: Path, prefix: str) -> list[tuple[str, int]]:
    """`#define <prefix>NAME ...`, in header order, values resolved.

    A value is either a literal or an `|` of names already defined, which is
    how the headers spell the "either shift key" masks. Anything else - the
    function-like `SDL_BUTTON_MASK` among them - is skipped.
    """
    pattern = re.compile(rf"^#define\s+{prefix}(\w+)\s+([^/\n]+)", re.M)
    out: list[tuple[str, int]] = []
    known: dict[str, int] = {}
    for match in pattern.finditer(header.read_text()):
        name, text = match.group(1), match.group(2).strip().rstrip("u")
        if literal := re.fullmatch(r"(0x[0-9A-Fa-f]+|\d+)u?", text):
            value = int(literal.group(1), 0)
        else:
            terms = [t.strip() for t in text.strip("()").split("|")]
            if not all(t.startswith(prefix) and t[len(prefix):] in known for t in terms):
                continue
            value = 0
            for term in terms:
                value |= known[term[len(prefix):]]
        known[name] = value
        out.append((name, value))
    return out


def keycodes_rs(include: Path) -> str:
    codes = scancodes(include / "SDL_scancode.h")
    mods = defines(include / "SDL_keycode.h", "SDL_KMOD_")
    lines = [
        BANNER.format(header="SDL_scancode.h and SDL_keycode.h"),
        "//! `SDL_Scancode` and `SDL_Keymod`, as SDL's headers declare them.",
        "",
        "/// `SDL_Scancode`, the USB HID keyboard usage IDs.",
        "pub mod scancode {",
    ]
    lines += [f"    pub const {name}: u32 = {value};" for name, value in codes]
    lines += ["}", "", "/// `SDL_Keymod` bits.", "pub mod keymod {"]
    lines += [f"    pub const {name}: u16 = {value:#06x};" for name, value in mods]
    lines.append("}")
    return "\n".join(lines) + "\n"


def mouse_rs(include: Path) -> str:
    buttons = defines(include / "SDL_mouse.h", "SDL_BUTTON_")
    lines = [
        BANNER.format(header="SDL_mouse.h"),
        "//! `SDL_BUTTON_*`: which button an `SDL_MouseButtonEvent` names.",
        "//!",
        "//! SDL numbers buttons from one and AppKit from zero, and the orders",
        "//! differ as well - see `appkit::button`.",
        "",
    ]
    lines += [f"pub const {name}: u8 = {value};" for name, value in buttons]
    lines += [
        "",
        "/// The bit a button holds in the mask `SDL_GetMouseState` returns.",
        "///",
        "/// `SDL_BUTTON_MASK(X)` in the header, which is a macro and so is not",
        "/// parsed out of it.",
        "pub const fn mask(button: u8) -> u32 {",
        "    1 << (button - 1)",
        "}",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--include-dir", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    include = args.include_dir or include_dir()
    generated = {
        OUT_DIR / "keycodes.rs": keycodes_rs(include),
        OUT_DIR / "mouse.rs": mouse_rs(include),
    }
    status = 0
    for path, text in generated.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                print(f"{path.relative_to(ROOT)} is not what {include} generates")
                status = 1
            continue
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")
    return status


if __name__ == "__main__":
    sys.exit(main())
